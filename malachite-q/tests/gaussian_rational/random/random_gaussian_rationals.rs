use itertools::Itertools;
use malachite_base::random::EXAMPLE_SEED;
use malachite_q::gaussian_rational::random::random_gaussian_rationals;

fn random_gaussian_rationals_helper(
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
    expected_values: &[&str],
) {
    assert_eq!(
        random_gaussian_rationals(EXAMPLE_SEED, mean_bits_numerator, mean_bits_denominator)
            .take(20)
            .map(|x| x.to_string())
            .collect_vec(),
        expected_values
    );
}

