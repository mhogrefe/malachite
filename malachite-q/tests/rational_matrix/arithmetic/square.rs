#[test]
#[should_panic]
fn square_fail() {
    let _ = RationalMatrix::from_str("[1/2, 2]").unwrap().square();
}

#[test]
#[should_panic]
fn square_ref_fail() {
    let _ = (&RationalMatrix::from_str("[1/2; 2]").unwrap()).square();
}

#[test]
#[should_panic]
fn square_assign_fail() {
    let mut a = RationalMatrix::from_str("[]_{0,2}").unwrap();
    a.square_assign();
}

#[test]
fn square_properties() {
    rational_matrix_gen_var_1().test_properties(|a| {
        let b = (&a).square();
        assert!(b.is_valid());
        assert_eq!((b.height(), b.width()), (a.height(), a.width()));
        assert_eq!(a.clone().square(), b);
        let mut c = a.clone();
        c.square_assign();
        assert!(c.is_valid());
        assert_eq!(c, b);
        assert_eq!(&a * &a, b);
        assert_eq!(rational_matrix_square_naive(&a), b);
        // The square of the transpose is the transpose of the square.
        assert_eq!(a.transpose().square(), b.transpose());
        // The square of the negative is the square.
        assert_eq!((-&a).square(), b);
        // These are slow for large matrices, whose squares have very large elements: over one
        // common denominator, the numerators grow with the number of distinct denominators.
        if a.height() <= 4 {
            assert_eq!(rational_matrix_square_matwise(&a), b);
            // The square commutes with the matrix.
            assert_eq!(&b * &a, &a * &b);
        }
    });

    integer_matrix_gen_var_1().test_properties(|a| {
        // The square agrees with the square of the `IntegerMatrix`.
        let a_square = (&a).square();
        assert_eq!(
            RationalMatrix::from(a.clone()).square(),
            RationalMatrix::from(a_square.clone())
        );
        // An integer matrix divided by d often has the denominator d in every row and column, and
        // its square is the integer matrix's square divided by d^2.
        for d in [2u32, 6, 1000000007] {
            let d = Natural::from(d);
            let r = RationalMatrix::from_numerators_and_denominator(&a, &d);
            let r_square = (&r).square();
            assert!(r_square.is_valid());
            assert_eq!(r.clone().square(), r_square);
            assert_eq!(mul_by_clearing_denominators(&r, &r), r_square);
            assert_eq!(
                RationalMatrix::from_numerators_and_denominator(&a_square, &(&d).square()),
                r_square
            );
        }
    });
}
