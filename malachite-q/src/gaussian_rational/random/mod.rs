use malachite_nz::natural::random::{RandomNaturals, StripedRandomNaturals};

#[doc(hidden)]
pub type RandomRationals = RandomRationalsFromDoubleAndSign<
    RandomNaturals<GeometricRandomNaturalValues<u64>>,
    RandomNaturals<GeometricRandomNaturalValues<u64>>,
>;

#[doc(hidden)]
pub type StripedRandomRationals = RandomRationalsFromDoubleAndSign<
    StripedRandomNaturals<GeometricRandomNaturalValues<u64>>,
    StripedRandomNaturals<GeometricRandomNaturalValues<u64>>,
>;

#[doc(hidden)]
pub type RandomGaussianRationalsFromPairs =
    Map<RandomPairsFromSingle<RandomRationals>, fn((Rational, Rational)) -> GaussianRational>;

#[doc(hidden)]
pub type StripedRandomGaussianRationalsFromPairs = Map<
    RandomPairsFromSingle<StripedRandomRationals>,
    fn((Rational, Rational)) -> GaussianRational,
>;

/// Generates random purely real [`GaussianRational`]s, whose real parts are generated by
/// [`random_rationals`] and have a specified mean bit length.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// Same as the complexity of [`random_rationals`].
///
/// # Panics
/// Panics if `mean_bits_numerator` or `mean_bits_denominator` are zero, or, if after being reduced
/// to lowest terms, their sum is greater than or equal to $2^{64}$.
///
/// # Examples
/// ```
/// use malachite_base::iterators::prefix_to_string;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_q::gaussian_rational::random::*;
///
/// assert_eq!(
///     prefix_to_string(random_real_gaussian_rationals(EXAMPLE_SEED, 32, 1), 4),
///     "[-7301/34, -4183103/1234731190583, 54812347098686/6195807891591254727, \
///     812739/17841539017, ...]"
/// )
/// ```
#[inline]
pub fn random_real_gaussian_rationals(
    seed: Seed,
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
) -> Map<RandomRationals, fn(Rational) -> GaussianRational> {
    random_rationals(seed, mean_bits_numerator, mean_bits_denominator).map(GaussianRational::from)
}

