/// Generates random [`GaussianRational`]s, whose real and imaginary parts are generated by
/// [`random_rationals`] and have a specified mean bit length.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// Same as the complexity of [`random_rationals`].
///
/// # Panics
/// Panics if `mean_bits_numerator` or `mean_bits_denominator` are zero, or, if after being reduced
/// to lowest terms, their sum is greater than or equal to $2^{64}$.
///
/// # Examples
/// ```
/// use malachite_base::iterators::prefix_to_string;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_q::gaussian_rational::random::*;
///
/// assert_eq!(
///     prefix_to_string(random_gaussian_rationals(EXAMPLE_SEED, 32, 1), 4),
///     "[-4183103/1234731190583-7301i/34, 812739/17841539017+54812347098686i/6195807891591254727, \
///     677/1138982845180-665i/908, 270142/5+166i/22491855393807861245619791028129, ...]"
/// )
/// ```
#[inline]
pub fn random_gaussian_rationals(
    seed: Seed,
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
) -> RandomGaussianRationalsFromPairs {
    random_pairs_from_single(random_rationals(
        seed,
        mean_bits_numerator,
        mean_bits_denominator,
    ))
    .map(gaussian_rational_from_pair)
}

/// Generates random purely real striped [`GaussianRational`]s, whose real parts are generated by
/// [`striped_random_rationals`] and have a specified mean bit length and mean stripe length.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// Same as the complexity of [`striped_random_rationals`].
///
/// # Panics
/// Panics if `mean_stripe_denominator` is zero, if `mean_stripe_numerator <
/// mean_stripe_denominator`, if `mean_bits_numerator` or `mean_bits_denominator` are zero, or, if
/// after being reduced to lowest terms, their sum is greater than or equal to $2^{64}$.
///
/// # Examples
/// ```
/// use malachite_base::iterators::prefix_to_string;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_q::gaussian_rational::random::*;
///
/// assert_eq!(
///     prefix_to_string(striped_random_real_gaussian_rationals(EXAMPLE_SEED, 16, 1, 32, 1), 4),
///     "[-8192/127, -16776704/4396972769407, 8796093005951/648518346332962816, 87381/2863267840, .\
///     ..]"
/// )
/// ```
#[inline]
pub fn striped_random_real_gaussian_rationals(
    seed: Seed,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
) -> Map<StripedRandomRationals, fn(Rational) -> GaussianRational> {
    striped_random_rationals(
        seed,
        mean_stripe_numerator,
        mean_stripe_denominator,
        mean_bits_numerator,
        mean_bits_denominator,
    )
    .map(GaussianRational::from)
}

