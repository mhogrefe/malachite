fn verify_det(a: &NaturalMatrix, m: &Natural) -> Natural {
    let d = a.mod_determinant(m);
    assert_eq!(a.clone().mod_determinant(m), d);
    assert_eq!(a.clone().mod_determinant(m.clone()), d);
    assert_eq!(a.mod_determinant(m.clone()), d);
    assert!(d < *m);
    assert_eq!(natural_matrix_mod_determinant_berkowitz(a, m), d);
    if a.height() <= 6 {
        assert_eq!(natural_matrix_mod_determinant_naive(a, m), d);
    }
    if let Some(e) = natural_matrix_mod_determinant_lu(a, m) {
        assert_eq!(e, d);
    }
    d
}

fn test(a: &str, m: &str, out: &str) {
    let a = NaturalMatrix::from_str(a).unwrap();
    let m = Natural::from_str(m).unwrap();
    assert_eq!(verify_det(&a, &m).to_string(), out);
}

