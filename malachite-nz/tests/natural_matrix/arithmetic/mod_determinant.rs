// `a` with its first two rows swapped.
fn swap_first_rows(a: &NaturalMatrix) -> NaturalMatrix {
    let n = a.height();
    let mut rows: Vec<Vec<Natural>> = (0..n).map(|i| a.row_iter(i).cloned().collect()).collect();
    rows.swap(0, 1);
    NaturalMatrix::from_owned_elements(n, n, rows.concat())
}

#[test]
fn mod_determinant_properties() {
    natural_matrix_natural_pair_gen_var_3().test_properties(|(a, m)| {
        let d = verify_det(&a, &m);
        assert_eq!(a.transpose().mod_determinant(&m), d);
        let at = a.transpose();
        assert_eq!(
            (&a).mod_mul(&at, &m).mod_determinant(&m),
            (&d).mod_mul(&d, &m)
        );
        if a.height() >= 2 {
            assert_eq!(swap_first_rows(&a).mod_determinant(&m), d.mod_neg(&m));
        }
    });

    natural_matrix_natural_pair_gen_var_6().test_properties(|(a, m)| {
        let d = verify_det(&a, &m);
        assert_eq!(natural_matrix_mod_determinant_lu(&a, &m), Some(d));
    });
}
