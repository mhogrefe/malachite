// The next output of the SplitMix64 generator with state `seed`.
const fn splitmix64(seed: &mut u64) -> u64 {
    *seed = seed.wrapping_add(0x9e3779b97f4a7c15);
    let mut z = *seed;
    z = (z ^ (z >> 30)).wrapping_mul(0xbf58476d1ce4e5b9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94d049bb133111eb);
    z ^ (z >> 31)
}

// A pseudorandom element less than `m`, made of several outputs of the SplitMix64 generator.
fn pseudorandom_natural(m: &Natural, seed: &mut u64) -> Natural {
    (0..3).fold(Natural::ZERO, |x, _| {
        (x << 64u32) + Natural::from(splitmix64(seed))
    }) % m
}

// A matrix with pseudorandom elements less than `m`.
fn pseudorandom_matrix(height: u64, width: u64, m: &Natural, seed: &mut u64) -> NaturalMatrix {
    let elements = (0..height * width)
        .map(|_| pseudorandom_natural(m, seed))
        .collect();
    NaturalMatrix::from_owned_elements(height, width, elements)
}

#[test]
fn test_mod_determinant_large() {
    let mut seed = 0;
    // - LU decomposition with a large prime modulus
    let p = Natural::from_str("170141183460469231731687303715884105727").unwrap();
    let a = pseudorandom_matrix(12, 12, &p, &mut seed);
    verify_det(&a, &p);
    // - LU decomposition fails at a pivot that is not invertible, so Berkowitz's algorithm is used
    let q = Natural::from_str("36893488147419103363").unwrap();
    let m = &p * &q;
    let mut a = pseudorandom_matrix(6, 6, &m, &mut seed);
    for i in 0..6 {
        let x = a.get(i, 0).unwrap() * &q % &m;
        *a.get_mut(i, 0).unwrap() = x;
    }
    assert_eq!(natural_matrix_mod_determinant_lu(&a, &m), None);
    verify_det(&a, &m);
}

