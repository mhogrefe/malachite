// Checks the characteristic polynomial modulo `m` of `a` in all four ways of calling it, against
// Berkowitz's algorithm, the reduction to Hessenberg form, Danilevsky's method when it succeeds,
// that of the transpose, and the characteristic polynomial of the corresponding `IntegerMatrix`,
// reduced modulo `m`, and, for small matrices, against the Cayley-Hamilton theorem, and returns it.
fn verify(a: &NaturalMatrix, m: &Natural) -> NaturalPolynomial {
    let p = a.mod_characteristic_polynomial(m);
    assert!(p.is_valid());
    assert_eq!(a.mod_characteristic_polynomial(m.clone()), p);
    assert_eq!(a.clone().mod_characteristic_polynomial(m), p);
    assert_eq!(a.clone().mod_characteristic_polynomial(m.clone()), p);
    assert_eq!(
        natural_matrix_mod_characteristic_polynomial_berkowitz(a, m),
        p
    );
    assert_eq!(
        natural_matrix_mod_characteristic_polynomial_hessenberg(a, m),
        p
    );
    if *m != 1u32
        && let Some(q) = natural_matrix_mod_characteristic_polynomial_danilevsky(a, m)
    {
        assert_eq!(q, p);
    }
    assert_eq!(a.transpose().mod_characteristic_polynomial(m), p);
    let integer_m = Integer::from(m);
    let coefficients = IntegerMatrix::from(a)
        .characteristic_polynomial()
        .into_coefficients_asc()
        .into_iter()
        .map(|c| Natural::exact_from(c.mod_op(&integer_m)))
        .collect();
    assert_eq!(NaturalPolynomial::from_coefficients_asc(coefficients), p);
    if a.height() <= 8 {
        assert!(natural_polynomial_mod_evaluate_at_matrix(&p, a, m).is_zero());
    }
    p
}

