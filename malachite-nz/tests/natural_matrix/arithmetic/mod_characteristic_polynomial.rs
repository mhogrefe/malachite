#[test]
fn test_charpoly_danilevsky() {
    let test = |s, m, out| {
        let a = NaturalMatrix::from_str(s).unwrap();
        let m = Natural::from_str(m).unwrap();
        assert_eq!(
            natural_matrix_mod_characteristic_polynomial_danilevsky(&a, &m)
                .unwrap()
                .to_string(),
            out
        );
    };
    // - dimension 0
    test("[]_{0,0}", "170141183460469231731687303715884105727", "1");
    // - dimension 1
    test(
        "[5]",
        "170141183460469231731687303715884105727",
        "x+170141183460469231731687303715884105722",
    );
}

#[test]
fn mod_characteristic_polynomial_fail() {
    // - not square
    let a = NaturalMatrix::from_str("[1, 2]").unwrap();
    assert_panic!((&a).mod_characteristic_polynomial(Natural::from(5u32)));
    // - not reduced
    let a = NaturalMatrix::from_str("[1, 2; 3, 9]").unwrap();
    assert_panic!((&a).mod_characteristic_polynomial(Natural::from(5u32)));
    // - m = 0
    let a = NaturalMatrix::from_str("[]_{0,0}").unwrap();
    assert_panic!((&a).mod_characteristic_polynomial(Natural::ZERO));
}

#[test]
fn mod_characteristic_polynomial_properties() {
    natural_matrix_natural_pair_gen_var_3().test_properties(|(a, m)| {
        let p = verify(&a, &m);
        // Modulo a power of 2, it agrees with the power-of-2 version.
        if m.is_power_of_2() {
            assert_eq!(
                (&a).mod_power_of_2_characteristic_polynomial(m.trailing_zeros().unwrap()),
                p
            );
        }
    });

    // Moduli with repeated prime factors, often of more than one limb.
    natural_matrix_natural_pair_gen_var_4().test_properties(|(a, m)| {
        if a.is_square() {
            verify(&a, &m);
        }
    });

    // For a prime modulus, Danilevsky's method succeeds.
    natural_matrix_natural_pair_gen_var_6().test_properties(|(a, m)| {
        assert_eq!(
            natural_matrix_mod_characteristic_polynomial_danilevsky(&a, &m),
            Some(verify(&a, &m))
        );
    });

    natural_matrix_unsigned_natural_natural_quadruple_gen_var_1().test_properties(
        |(a, r, d, m)| {
            // Similar matrices have the same characteristic polynomial.
            assert_eq!(
                (&a).mod_similarity_transform(r, &d, &m)
                    .mod_characteristic_polynomial(&m),
                verify(&a, &m)
            );
        },
    );

    // The word-sized characteristic polynomials agree with those of the corresponding
    // NaturalMatrix.
    unsigned_matrix_unsigned_pair_gen_var_11().test_properties(|(a, m)| {
        let coefficients = (&a)
            .mod_characteristic_polynomial(m)
            .into_coefficients_asc()
            .into_iter()
            .map(Natural::from)
            .collect();
        assert_eq!(
            NaturalPolynomial::from_coefficients_asc(coefficients),
            NaturalMatrix::from(a).mod_characteristic_polynomial(Natural::from(m))
        );
    });
}
