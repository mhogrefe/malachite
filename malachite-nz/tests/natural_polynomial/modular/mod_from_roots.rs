#[test]
#[should_panic]
fn mod_from_roots_fail_1() {
    // m is 0.
    NaturalPolynomial::mod_from_roots(&[], &Natural::ZERO);
}

#[test]
#[should_panic]
fn mod_from_roots_fail_2() {
    // A root is not reduced.
    NaturalPolynomial::mod_from_roots(&[Natural::ONE, Natural::from(7u32)], &Natural::from(7u32));
}

#[test]
fn mod_from_roots_properties() {
    let test = |(xs, m): (Vec<Natural>, Natural)| {
        let p = NaturalPolynomial::mod_from_roots(&xs, &m);
        assert!(p.is_valid());
        assert!(p.mod_is_reduced(&m));
        assert_eq!(NaturalPolynomial::mod_from_roots(&xs, m.clone()), p);
        assert_eq!(mod_from_roots_naive(&xs, &m), p);
        assert_eq!(p.len(), u64::try_from(xs.len()).unwrap() + 1);
        assert_eq!(*p.leading_coefficient(), 1u32);
        for x in &xs {
            assert_eq!((&p).mod_evaluate(x, &m), 0u32);
        }
        let mut ys = xs.clone();
        ys.reverse();
        assert_eq!(NaturalPolynomial::mod_from_roots(&ys, &m), p);
        let (xs_1, xs_2) = xs.split_at(xs.len() >> 1);
        assert_eq!(
            NaturalPolynomial::mod_from_roots(xs_1, &m)
                .mod_mul(NaturalPolynomial::mod_from_roots(xs_2, &m), &m),
            p
        );
    };
    natural_vec_natural_pair_gen_var_2().test_properties(test);

    // Long enough to split into products of the halves.
    let mut config = GenConfig::new();
    config.insert("mean_length_n", 32);
    config.insert("mean_length_d", 1);
    natural_vec_natural_pair_gen_var_2().test_properties_with_config(&config, test);
}
