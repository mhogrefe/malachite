fn verify_truncated(n: u64, len: u64) -> NaturalPolynomial {
    let p = NaturalPolynomial::touchard_polynomial_truncated(n, len);
    assert!(p.is_valid());
    assert_eq!(touchard_polynomial_truncated_naive(n, len), p);
    assert_eq!(touchard_polynomial_truncated_triangular(n, len), p);
    assert_eq!(touchard_polynomial_truncated_convolution(n, len), p);
    assert_eq!(touchard_polynomial_truncated_multi_mod(n, len), p);
    p
}

#[test]
fn test_touchard_polynomial() {
    fn test(n: u64, out: &str) {
        let p = NaturalPolynomial::touchard_polynomial(n);
        assert_eq!(p.to_string(), out);
        assert_eq!(verify_truncated(n, n + 1), p);
    }
    // - k >= n in the tails of the recurrence and the convolution
    // - n <= 2 in the multimodular computation
    // - n <= 80 in the dispatch
    test(0, "1");
    // - n <= MAX_N_1LIMB
    test(1, "x");
    // - n >= 1 && len >= 1 in the convolution, with k = kodd
    test(2, "x^2+x");
    // - k = kodd * 2^e with e > 0 in the convolution
    // - len > 1 and i prime in the modular powers
    // - a single resolution level and a single prime
    test(3, "x^3+3*x^2+x");
    // - m < klen and the recurrence in triangular_1
    // - i composite in the modular powers
    test(4, "x^4+6*x^3+7*x^2+x");
    test(5, "x^5+10*x^4+25*x^3+15*x^2+x");
    test(6, "x^6+15*x^5+65*x^4+90*x^3+31*x^2+x");
}

