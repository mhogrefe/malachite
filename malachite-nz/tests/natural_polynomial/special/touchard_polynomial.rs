#[test]
fn test_touchard_polynomial_truncated_large() {
    // Rows too long to write out: every algorithm, and the naive reference, must agree, and the
    // coefficients of a whole row must sum to the Bell number.
    let test = |n: u64, len: u64| {
        let p = verify_truncated(n, len);
        assert_eq!(p.len(), len.min(n + 1));
        if len > n {
            assert_eq!((&p).evaluate(&Natural::ONE), Natural::bell_number(n));
        }
    };
    // - n / 4 < len <= n / 2 and n > 450 in the dispatch
    test(500, 200);
    // - 2 * len > n and n > 750 in the dispatch
    test(800, 801);
}

#[test]
fn touchard_polynomial_properties() {
    // n is kept below 256: the nth row has n + 1 coefficients of about n log n bits, and the naive
    // reference fills the whole triangle.
    unsigned_gen_var_5::<u8>().test_properties(|n| {
        let n = u64::from(n);
        let p = NaturalPolynomial::touchard_polynomial(n);
        assert_eq!(verify_truncated(n, n + 1), p);
        assert_eq!(p.len(), n + 1);
        assert_eq!(*p.coefficient(n), 1u32);
        assert_eq!(*p.coefficient(0), u32::from(n == 0));
        // The coefficients of the nth Touchard polynomial sum to the nth Bell number.
        assert_eq!((&p).evaluate(&Natural::ONE), Natural::bell_number(n));
        // S(n, n - 1) is the binomial coefficient C(n, 2), and S(n, 2) is 2^(n - 1) - 1.
        if n >= 1 {
            assert_eq!(
                *p.coefficient(n - 1),
                Natural::binomial_coefficient(Natural::from(n), Natural::TWO)
            );
        }
        if n >= 2 {
            assert_eq!(*p.coefficient(2), Natural::power_of_2(n - 1) - Natural::ONE);
        }
        // T_(n + 1)(x) = x(T_n(x) + T_n'(x)).
        assert_eq!(
            NaturalPolynomial::touchard_polynomial(n + 1),
            (&p + (&p).derivative()).mul_power_of_x(1)
        );
    });

    unsigned_pair_gen_var_28::<u8, u8>().test_properties(|(n, len)| {
        let (n, len) = (u64::from(n), u64::from(len));
        let p = verify_truncated(n, len);
        // Truncation keeps a prefix of the coefficients.
        let full = NaturalPolynomial::touchard_polynomial(n);
        let prefix: Vec<Natural> = (0..len).map(|k| full.coefficient(k).clone()).collect();
        assert_eq!(p, NaturalPolynomial::from_coefficients_asc(prefix));
        assert!(p.len() <= len);
        if len > n {
            assert_eq!(p, full);
        }
        if len == 0 || n > 0 && len == 1 {
            assert_eq!(p, NaturalPolynomial::ZERO);
        }
    });
}
