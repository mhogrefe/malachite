#[test]
fn mul_high_to_out_karatsuba_n_properties() {
    let mut config = GenConfig::new();
    config.insert("mean_len_n", 32);
    let test = |(xs, ys): (Vec<Integer>, Vec<Integer>)| {
        let len = xs.len();
        let mut out = vec![Integer::ZERO; (len << 1) - 1];
        mul_high_to_out_karatsuba_n(&mut out, &xs, &ys);
        assert!(out.iter().all(Integer::is_valid));
        assert!(out[..len - 1].iter().all(|x| *x == 0u32));
        assert_eq!(&integers_mul_naive(&xs, &ys)[len - 1..], &out[len - 1..]);
        let mut out_alt = vec![Integer::ZERO; (len << 1) - 1];
        mul_high_to_out_classical(&mut out_alt, &xs, &ys, len - 1);
        assert_eq!(out_alt, out);
    };
    integer_vec_pair_gen_var_4().test_properties(test);
    integer_vec_pair_gen_var_4().test_properties_with_config(&config, test);
}

