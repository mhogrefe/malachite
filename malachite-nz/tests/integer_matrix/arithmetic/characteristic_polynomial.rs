// Checks the characteristic polynomial against every algorithm that applies, and returns it.
fn verify(a: &IntegerMatrix) -> IntegerPolynomial {
    let p = a.characteristic_polynomial();
    assert!(p.is_valid());
    assert_eq!(a.clone().characteristic_polynomial(), p);
    let n = usize::exact_from(a.height());
    assert_eq!(
        IntegerPolynomial::from_coefficients_asc(charpoly_berkowitz(a.elements_ref(), n)),
        p
    );
    assert_eq!(
        IntegerPolynomial::from_coefficients_asc(charpoly_modular(a)),
        p
    );
    if n <= 7 {
        assert_eq!(integer_matrix_characteristic_polynomial_naive(a), p);
    }
    // The Cayley-Hamilton theorem: a matrix satisfies its characteristic polynomial.
    if n <= 8 {
        assert!(integer_polynomial_evaluate_at_matrix(&p, a).is_zero());
    }
    p
}

