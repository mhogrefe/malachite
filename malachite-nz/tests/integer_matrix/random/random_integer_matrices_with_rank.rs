use itertools::Itertools;
use malachite_base::random::EXAMPLE_SEED;
use malachite_nz::integer_matrix::random::random_integer_matrices_with_rank;

fn random_integer_matrices_with_rank_helper(
    height: u64,
    width: u64,
    rank: u64,
    bits: u64,
    expected_values: &[&str],
) {
    assert_eq!(
        random_integer_matrices_with_rank(EXAMPLE_SEED, height, width, rank, bits)
            .map(|m| m.to_string())
            .take(20)
            .collect_vec(),
        expected_values
    );
}

