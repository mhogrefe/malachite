use crate::mag::{MAG_BITS, MAG_ONE_HALF, Mag};
use malachite_base::bools::random::{WeightedRandomBools, weighted_random_bools};
use malachite_base::num::arithmetic::traits::PowerOf2;
use malachite_base::num::random::geometric::{GeometricRandomSigneds, geometric_random_signeds};
use malachite_base::num::random::striped::{
    StripedRandomUnsignedInclusiveRange, striped_random_unsigned_range,
};
use malachite_base::num::random::{RandomUnsignedRange, random_unsigned_range};
use malachite_base::random::Seed;

// Generates random positive `Mag`s, from an iterator of mantissas and geometrically distributed
// exponents.
#[derive(Clone, Debug)]
pub struct RandomPositiveMags<I: Iterator<Item = u64>> {
    exponents: GeometricRandomSigneds<i64>,
    mantissas: I,
}

impl<I: Iterator<Item = u64>> Iterator for RandomPositiveMags<I> {
    type Item = Mag;

    #[inline]
    fn next(&mut self) -> Option<Mag> {
        Some(Mag {
            man: self.mantissas.next().unwrap(),
            exp: self.exponents.next().unwrap(),
        })
    }
}

// Generates random positive `Mag`s, whose mantissas are uniformly distributed among the `MAG_BITS`-
// bit values and whose exponents have a geometric distribution, with the mean absolute value given
// by `mean_exponent_abs_numerator / mean_exponent_abs_denominator` (approximately, since the
// distribution is truncated to the range of an `i64`). A `Mag` with exponent e lies in
// [2^(e - 1), 2^e).
//
// # Panics
// Panics if `mean_exponent_abs_numerator` or `mean_exponent_abs_denominator` is zero, or if their
// ratio is too large for the geometric distribution.
pub fn random_positive_mags(
    seed: Seed,
    mean_exponent_abs_numerator: u64,
    mean_exponent_abs_denominator: u64,
) -> RandomPositiveMags<RandomUnsignedRange<u64>> {
    RandomPositiveMags {
        exponents: geometric_random_signeds(
            seed.fork("exponents"),
            mean_exponent_abs_numerator,
            mean_exponent_abs_denominator,
        ),
        mantissas: random_unsigned_range(
            seed.fork("mantissas"),
            MAG_ONE_HALF,
            u64::power_of_2(MAG_BITS),
        ),
    }
}

// Generates striped random positive `Mag`s: their mantissas are generated by
// `striped_random_unsigned_range`, so they have long runs of 0s and 1s, with mean run length
// `mean_stripe_numerator / mean_stripe_denominator`. This makes values just above and below powers
// of 2, whose rounding can carry into the next power of 2, common. The exponents are as in
// `random_positive_mags`.
//
// # Panics
// Panics if any numerator or denominator is zero, if the mean exponent is too large for the
// geometric distribution, or if the mean stripe length is less than 1.
pub fn striped_random_positive_mags(
    seed: Seed,
    mean_exponent_abs_numerator: u64,
    mean_exponent_abs_denominator: u64,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
) -> RandomPositiveMags<StripedRandomUnsignedInclusiveRange<u64>> {
    RandomPositiveMags {
        exponents: geometric_random_signeds(
            seed.fork("exponents"),
            mean_exponent_abs_numerator,
            mean_exponent_abs_denominator,
        ),
        mantissas: striped_random_unsigned_range(
            seed.fork("mantissas"),
            MAG_ONE_HALF,
            u64::power_of_2(MAG_BITS),
            mean_stripe_numerator,
            mean_stripe_denominator,
        ),
    }
}

// Generates random `Mag`s, zero with a given probability and otherwise positive.
#[derive(Clone, Debug)]
pub struct RandomMags<I: Iterator<Item = u64>> {
    bs: WeightedRandomBools,
    xs: RandomPositiveMags<I>,
}

impl<I: Iterator<Item = u64>> Iterator for RandomMags<I> {
    type Item = Mag;

    #[inline]
    fn next(&mut self) -> Option<Mag> {
        if self.bs.next().unwrap() {
            Some(Mag::ZERO)
        } else {
            self.xs.next()
        }
    }
}

// Generates random `Mag`s: zero with probability `zero_p_numerator / zero_p_denominator`, and
// otherwise a `Mag` from `random_positive_mags`.
//
// # Panics
// Panics under the conditions of `random_positive_mags`, if `zero_p_denominator` is zero, or if
// `zero_p_numerator > zero_p_denominator`.
pub fn random_mags(
    seed: Seed,
    mean_exponent_abs_numerator: u64,
    mean_exponent_abs_denominator: u64,
    zero_p_numerator: u64,
    zero_p_denominator: u64,
) -> RandomMags<RandomUnsignedRange<u64>> {
    RandomMags {
        bs: weighted_random_bools(seed.fork("bs"), zero_p_numerator, zero_p_denominator),
        xs: random_positive_mags(
            seed.fork("xs"),
            mean_exponent_abs_numerator,
            mean_exponent_abs_denominator,
        ),
    }
}

// Generates striped random `Mag`s: zero with probability `zero_p_numerator / zero_p_denominator`,
// and otherwise a `Mag` from `striped_random_positive_mags`.
//
// # Panics
// Panics under the conditions of `striped_random_positive_mags`, if `zero_p_denominator` is zero,
// or if `zero_p_numerator > zero_p_denominator`.
pub fn striped_random_mags(
    seed: Seed,
    mean_exponent_abs_numerator: u64,
    mean_exponent_abs_denominator: u64,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
    zero_p_numerator: u64,
    zero_p_denominator: u64,
) -> RandomMags<StripedRandomUnsignedInclusiveRange<u64>> {
    RandomMags {
        bs: weighted_random_bools(seed.fork("bs"), zero_p_numerator, zero_p_denominator),
        xs: striped_random_positive_mags(
            seed.fork("xs"),
            mean_exponent_abs_numerator,
            mean_exponent_abs_denominator,
            mean_stripe_numerator,
            mean_stripe_denominator,
        ),
    }
}
