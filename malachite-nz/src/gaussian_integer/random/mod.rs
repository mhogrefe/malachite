/// Generates random [`GaussianInteger`]s, whose real and imaginary parts are generated by
/// [`random_integers`] and have a specified mean bit length.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// Same as the complexity of [`random_integers`].
///
/// # Panics
/// Panics if `mean_bits_numerator` or `mean_bits_denominator` are zero, or, if after being reduced
/// to lowest terms, their sum is greater than or equal to $2^{64}$.///
/// # Examples
/// ```
/// use malachite_base::iterators::prefix_to_string;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_nz::gaussian_integer::random::*;
///
/// assert_eq!(
///     prefix_to_string(random_gaussian_integers(EXAMPLE_SEED, 32, 1), 6),
///     "[69403499476962893258904+89270i, -1848070042786+62i, -696-64671510460i, -79, \
///     7330+70819i, -424643+215441i, ...]"
/// )
/// ```
#[inline]
pub fn random_gaussian_integers(
    seed: Seed,
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
) -> Map<
    RandomPairsFromSingle<RandomIntegers<GeometricRandomSigneds<i64>>>,
    fn((Integer, Integer)) -> GaussianInteger,
> {
    random_pairs_from_single(random_integers(
        seed,
        mean_bits_numerator,
        mean_bits_denominator,
    ))
    .map(gaussian_integer_from_pair)
}

/// Generates random purely real striped [`GaussianInteger`]s, whose real parts are generated by
/// [`striped_random_integers`] and have a specified mean bit length and mean stripe length.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// Same as the complexity of [`striped_random_integers`].
///
/// # Panics
/// Panics if `mean_stripe_denominator` is zero, if `mean_stripe_numerator <
/// mean_stripe_denominator`, if `mean_bits_numerator` or `mean_bits_denominator` are zero, or, if
/// after being reduced to lowest terms, their sum is greater than or equal to $2^{64}$.///
/// # Examples
/// ```
/// use malachite_base::iterators::prefix_to_string;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_nz::gaussian_integer::random::*;
///
/// assert_eq!(
///     prefix_to_string(
///         striped_random_real_gaussian_integers(EXAMPLE_SEED, 16, 1, 32, 1),
///         6
///     ),
///     "[65536, 75521006248971741167616, 32, -2199023255520, -68719468544, -527, ...]"
/// )
/// ```
#[inline]
pub fn striped_random_real_gaussian_integers(
    seed: Seed,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
) -> Map<StripedRandomIntegers<GeometricRandomSigneds<i64>>, fn(Integer) -> GaussianInteger> {
    striped_random_integers(
        seed,
        mean_stripe_numerator,
        mean_stripe_denominator,
        mean_bits_numerator,
        mean_bits_denominator,
    )
    .map(GaussianInteger::from)
}

