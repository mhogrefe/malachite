/// Generates random purely real [`GaussianInteger`]s, whose real parts are generated by
/// [`random_integers`] and have a specified mean bit length.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// Same as the complexity of [`random_integers`].
///
/// # Panics
/// Panics if `mean_bits_numerator` or `mean_bits_denominator` are zero, or, if after being reduced
/// to lowest terms, their sum is greater than or equal to $2^{64}$.///
/// # Examples
/// ```
/// use malachite_base::iterators::prefix_to_string;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_nz::gaussian_integer::random::*;
///
/// assert_eq!(
///     prefix_to_string(random_real_gaussian_integers(EXAMPLE_SEED, 32, 1), 6),
///     "[89270, 69403499476962893258904, 62, -1848070042786, -64671510460, -696, ...]"
/// )
/// ```
#[inline]
pub fn random_real_gaussian_integers(
    seed: Seed,
    mean_bits_numerator: u64,
    mean_bits_denominator: u64,
) -> Map<RandomIntegers<GeometricRandomSigneds<i64>>, fn(Integer) -> GaussianInteger> {
    random_integers(seed, mean_bits_numerator, mean_bits_denominator).map(GaussianInteger::from)
}

