/// Generates random non-negative or non-positive finite [`BigExponentFloat`]s.
///
/// This `struct` is created by the `random_non_negative_*`, `random_non_positive_*`, and
/// corresponding striped functions; see their documentation for more.
#[derive(Clone, Debug)]
pub struct RandomSignedOrZeroFiniteBigExponentFloats<
    I: Iterator<Item = Integer>,
    J: Iterator<Item = Natural>,
> {
    sign: bool,
    bs: WeightedRandomBools,
    xs: RandomPositiveFiniteBigExponentFloats<I, J>,
}

impl<I: Iterator<Item = Integer>, J: Iterator<Item = Natural>> Iterator
    for RandomSignedOrZeroFiniteBigExponentFloats<I, J>
{
    type Item = BigExponentFloat;

    #[inline]
    fn next(&mut self) -> Option<BigExponentFloat> {
        Some(if self.bs.next().unwrap() {
            BigExponentFloat::ZERO
        } else if self.sign {
            self.xs.next().unwrap()
        } else {
            self.xs.next().unwrap().negate()
        })
    }
}

/// Generates random non-negative finite [`BigExponentFloat`]s.
///
/// Zero is generated with probability `zero_p_numerator / zero_p_denominator`; the other values are
/// those of [`random_positive_finite_big_exponent_floats`].
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// $T(n, m) = O(n + m)$
///
/// $M(n, m) = O(n + m)$
///
/// where $T$ is time, $M$ is additional memory, $n$ is `mean_precision_numerator /
/// mean_precision_denominator`, and $m$ is `mean_exponent_bits_numerator /
/// mean_exponent_bits_denominator`.
///
/// # Panics
/// Panics under the conditions of [`random_positive_finite_big_exponent_floats`], if
/// `zero_p_denominator` is zero, or if `zero_p_numerator > zero_p_denominator`.
///
/// # Examples
/// ```
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_float::big_exponent_float::random::*;
///
/// assert!(
///     random_non_negative_finite_big_exponent_floats(EXAMPLE_SEED, 2, 1, 4, 1, 1, 10)
///         .take(100)
///         .all(|x| x.is_sign_positive())
/// );
/// ```
pub fn random_non_negative_finite_big_exponent_floats(
    seed: Seed,
    mean_exponent_bits_numerator: u64,
    mean_exponent_bits_denominator: u64,
    mean_precision_numerator: u64,
    mean_precision_denominator: u64,
    zero_p_numerator: u64,
    zero_p_denominator: u64,
) -> RandomSignedOrZeroFiniteBigExponentFloats<RandomExponents, RandomSignificands> {
    RandomSignedOrZeroFiniteBigExponentFloats {
        sign: true,
        bs: weighted_random_bools(seed.fork("bs"), zero_p_numerator, zero_p_denominator),
        xs: random_positive_finite_big_exponent_floats(
            seed.fork("xs"),
            mean_exponent_bits_numerator,
            mean_exponent_bits_denominator,
            mean_precision_numerator,
            mean_precision_denominator,
        ),
    }
}

