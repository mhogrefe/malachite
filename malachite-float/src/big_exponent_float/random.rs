/// Each of $\infty$, $-\infty$, and NaN is generated with probability `mean_special_p_numerator /
/// (3 * mean_special_p_denominator)`, and zero, among the finite values, with probability
/// `mean_special_p_numerator / mean_special_p_denominator`; the other values are those of
/// [`random_nonzero_finite_big_exponent_floats`].
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// $T(n, m) = O(n + m)$
///
/// $M(n, m) = O(n + m)$
///
