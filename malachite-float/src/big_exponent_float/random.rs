/// Generates random nonzero finite [`BigExponentFloat`]s.
///
/// This `struct` is created by [`random_nonzero_finite_big_exponent_floats`] and
/// [`striped_random_nonzero_finite_big_exponent_floats`]; see their documentation for more.
#[derive(Clone, Debug)]
pub struct RandomNonzeroFiniteBigExponentFloats<
    I: Iterator<Item = Integer>,
    J: Iterator<Item = Natural>,
> {
    bs: RandomBools,
    xs: RandomPositiveFiniteBigExponentFloats<I, J>,
}

impl<I: Iterator<Item = Integer>, J: Iterator<Item = Natural>> Iterator
    for RandomNonzeroFiniteBigExponentFloats<I, J>
{
    type Item = BigExponentFloat;

    #[inline]
    fn next(&mut self) -> Option<BigExponentFloat> {
        let x = self.xs.next().unwrap();
        Some(if self.bs.next().unwrap() {
            x
        } else {
            negate(x)
        })
    }
}

