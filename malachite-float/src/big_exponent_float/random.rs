/// Generates random finite [`BigExponentFloat`]s.
///
/// This `struct` is created by [`random_finite_big_exponent_floats`] and
/// [`striped_random_finite_big_exponent_floats`]; see their documentation for more.
#[derive(Clone, Debug)]
pub struct RandomFiniteBigExponentFloats<I: Iterator<Item = Integer>, J: Iterator<Item = Natural>> {
    bs: WeightedRandomBools,
    xs: RandomNonzeroFiniteBigExponentFloats<I, J>,
}

impl<I: Iterator<Item = Integer>, J: Iterator<Item = Natural>> Iterator
    for RandomFiniteBigExponentFloats<I, J>
{
    type Item = BigExponentFloat;

    #[inline]
    fn next(&mut self) -> Option<BigExponentFloat> {
        if self.bs.next().unwrap() {
            Some(BigExponentFloat::ZERO)
        } else {
            self.xs.next()
        }
    }
}

