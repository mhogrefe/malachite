/// The exponent generator of the random [`BigExponentFloat`] generators.
pub type RandomExponents = RandomIntegers<GeometricRandomSigneds<i64>>;

/// The exponent generator of the striped random [`BigExponentFloat`] generators.
pub type StripedRandomExponents = StripedRandomIntegers<GeometricRandomSigneds<i64>>;

/// The significand generator of the random [`BigExponentFloat`] generators.
pub type RandomSignificands = RandomNaturals<GeometricRandomNaturalValues<u64>>;

/// The significand generator of the striped random [`BigExponentFloat`] generators.
pub type StripedRandomSignificands = StripedRandomNaturals<GeometricRandomNaturalValues<u64>>;

fn negate(mut x: BigExponentFloat) -> BigExponentFloat {
    if let BigExponentFloat(Finite { sign, .. }) = &mut x {
        sign.not_assign();
    }
    x
}

/// Generates random positive finite [`BigExponentFloat`]s.
///
/// This `struct` is created by [`random_positive_finite_big_exponent_floats`] and
/// [`striped_random_positive_finite_big_exponent_floats`]; see their documentation for more.
#[derive(Clone, Debug)]
pub struct RandomPositiveFiniteBigExponentFloats<
    I: Iterator<Item = Integer>,
    J: Iterator<Item = Natural>,
> {
    sci_exponents: I,
    significands: J,
}

impl<I: Iterator<Item = Integer>, J: Iterator<Item = Natural>> Iterator
    for RandomPositiveFiniteBigExponentFloats<I, J>
{
    type Item = BigExponentFloat;

    #[inline]
    fn next(&mut self) -> Option<BigExponentFloat> {
        Some(BigExponentFloat::from_parts(
            true,
            self.sci_exponents.next().unwrap() + Integer::ONE,
            self.significands.next().unwrap(),
        ))
    }
}

/// Generates random positive finite [`BigExponentFloat`]s.
///
/// The sci-exponent of a positive [`BigExponentFloat`] $m2^e$, with $1\leq m<2$, is $e$. It is
/// generated by [`random_integers`], so its number of bits has a geometric distribution whose mean
/// is approximately `mean_exponent_bits_numerator / mean_exponent_bits_denominator`; exponents
/// larger than any primitive integer occur, though rarely when the mean is small. The significand
/// is generated by [`random_positive_naturals`], with a mean number of bits of approximately
/// `mean_precision_numerator / mean_precision_denominator`, and its trailing zeros are dropped, so
/// the precision of the output is at most that number of bits.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// $T(n, m) = O(n + m)$
///
/// $M(n, m) = O(n + m)$
///
/// where $T$ is time, $M$ is additional memory, $n$ is `mean_precision_numerator /
/// mean_precision_denominator`, and $m$ is `mean_exponent_bits_numerator /
/// mean_exponent_bits_denominator`.
///
/// # Panics
/// Panics if `mean_precision_numerator` or `mean_precision_denominator` are zero, if their ratio
/// is less than 1, or if `mean_exponent_bits_denominator` is zero.
///
/// # Examples
/// ```
/// use itertools::Itertools;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_float::big_exponent_float::random::*;
///
/// assert_eq!(
///     random_positive_finite_big_exponent_floats(EXAMPLE_SEED, 2, 1, 4, 1)
///         .take(4)
///         .map(|x| format!("{x:#x}"))
///         .collect_vec()
///         .len(),
///     4
/// );
/// ```
pub fn random_positive_finite_big_exponent_floats(
    seed: Seed,
    mean_exponent_bits_numerator: u64,
    mean_exponent_bits_denominator: u64,
    mean_precision_numerator: u64,
    mean_precision_denominator: u64,
) -> RandomPositiveFiniteBigExponentFloats<RandomExponents, RandomSignificands> {
    RandomPositiveFiniteBigExponentFloats {
        sci_exponents: random_integers(
            seed.fork("exponents"),
            mean_exponent_bits_numerator,
            mean_exponent_bits_denominator,
        ),
        significands: random_positive_naturals(
            seed.fork("significands"),
            mean_precision_numerator,
            mean_precision_denominator,
        ),
    }
}

/// Generates striped random positive finite [`BigExponentFloat`]s.
///
/// This is like [`random_positive_finite_big_exponent_floats`], except that the sci-exponent and
/// the significand are generated by [`striped_random_integers`] and
/// [`striped_random_positive_naturals`], so their bits come in long runs of 0s and 1s, with mean
/// run length `mean_stripe_numerator / mean_stripe_denominator`. Significands just below a power
/// of 2, whose rounding carries into the exponent, are therefore common.
///
/// The output length is infinite.
///
/// # Expected complexity per iteration
/// $T(n, m) = O(n + m)$
///
/// $M(n, m) = O(n + m)$
///
/// where $T$ is time, $M$ is additional memory, $n$ is `mean_precision_numerator /
/// mean_precision_denominator`, and $m$ is `mean_exponent_bits_numerator /
/// mean_exponent_bits_denominator`.
///
/// # Panics
/// Panics if `mean_stripe_denominator` is zero, if `mean_stripe_numerator <
/// mean_stripe_denominator`, if `mean_precision_numerator` or `mean_precision_denominator` are
/// zero, if their ratio is less than 1, or if `mean_exponent_bits_denominator` is zero.
///
/// # Examples
/// ```
/// use itertools::Itertools;
/// use malachite_base::random::EXAMPLE_SEED;
/// use malachite_float::big_exponent_float::random::*;
///
/// assert_eq!(
///     striped_random_positive_finite_big_exponent_floats(EXAMPLE_SEED, 2, 1, 4, 1, 4, 1)
///         .take(4)
///         .map(|x| format!("{x:#x}"))
///         .collect_vec()
///         .len(),
///     4
/// );
/// ```
pub fn striped_random_positive_finite_big_exponent_floats(
    seed: Seed,
    mean_exponent_bits_numerator: u64,
    mean_exponent_bits_denominator: u64,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
    mean_precision_numerator: u64,
    mean_precision_denominator: u64,
) -> RandomPositiveFiniteBigExponentFloats<StripedRandomExponents, StripedRandomSignificands> {
    RandomPositiveFiniteBigExponentFloats {
        sci_exponents: striped_random_integers(
            seed.fork("exponents"),
            mean_stripe_numerator,
            mean_stripe_denominator,
            mean_exponent_bits_numerator,
            mean_exponent_bits_denominator,
        ),
        significands: striped_random_positive_naturals(
            seed.fork("significands"),
            mean_stripe_numerator,
            mean_stripe_denominator,
            mean_precision_numerator,
            mean_precision_denominator,
        ),
    }
}

/// Generates random negative finite [`BigExponentFloat`]s.
///
/// This `struct` is created by [`random_negative_finite_big_exponent_floats`] and
/// [`striped_random_negative_finite_big_exponent_floats`]; see their documentation for more.
#[derive(Clone, Debug)]
pub struct RandomNegativeFiniteBigExponentFloats<
    I: Iterator<Item = Integer>,
    J: Iterator<Item = Natural>,
>(RandomPositiveFiniteBigExponentFloats<I, J>);

impl<I: Iterator<Item = Integer>, J: Iterator<Item = Natural>> Iterator
    for RandomNegativeFiniteBigExponentFloats<I, J>
{
    type Item = BigExponentFloat;

    #[inline]
    fn next(&mut self) -> Option<BigExponentFloat> {
        self.0.next().map(negate)
    }
}

