// nonzero and did not overflow or underflow is also checked against the algorithm-independent
// rounding check, applied to W(-x) = -T(x).
fn check_rounding(x: &Float, tree_t0: &Float, o: Ordering, prec: u64, rm: RoundingMode) {
    let (w, wo) = (-x).lambert_w0_prec_round(prec, -rm);
    assert_eq!(ComparableFloatRef(&-w), ComparableFloatRef(tree_t0));
    assert_eq!(wo.reverse(), o);
    if rm != Exact && tree_t0.is_normal() && result_in_range(tree_t0, o) {
        let neg_x = float_to_big_exponent_float(&-x);
        assert_lambert_w_correctly_rounded(
            true,
            &|f| f.partial_cmp(&neg_x).unwrap(),
            Some(&neg_x),
            &float_to_big_exponent_float(&-tree_t0),
            o.reverse(),
            prec,
            -rm,
        );
    }
}

#[allow(clippy::needless_pass_by_value)]
fn tree_t0_prec_round_properties_helper(x: Float, prec: u64, rm: RoundingMode) {
    let (tree_t0, o) = x.clone().tree_t0_prec_round(prec, rm);
    assert!(tree_t0.is_valid());
    assert_rounding_ordering_consistent(&tree_t0, rm, o);

    let (tree_t0_alt, o_alt) = x.tree_t0_prec_round_ref(prec, rm);
    assert!(tree_t0_alt.is_valid());
    assert_eq!(
        ComparableFloatRef(&tree_t0_alt),
        ComparableFloatRef(&tree_t0)
    );
    assert_eq!(o_alt, o);

    let mut x_alt = x.clone();
    let o_alt = x_alt.tree_t0_prec_round_assign(prec, rm);
    assert!(x_alt.is_valid());
    assert_eq!(ComparableFloatRef(&x_alt), ComparableFloatRef(&tree_t0));
    assert_eq!(o_alt, o);

    check_rounding(&x, &tree_t0, o, prec, rm);

    if tree_t0.is_normal() {
        assert_eq!(tree_t0.get_prec(), Some(prec));
    }
    if x <= 0u32 {
        if !tree_t0.is_nan() {
            assert_eq!(tree_t0.is_sign_negative(), x.is_sign_negative());
        }
    } else if tree_t0.is_normal() {
        // T_0 maps (0, 1/e) to (0, 1).
        assert!(tree_t0 >= 0u32);
        assert!(tree_t0 <= 1u32);
    }

    if o == Equal {
        for rm in exhaustive_rounding_modes() {
            let (s, oo) = x.tree_t0_prec_round_ref(prec, rm);
            assert_eq!(ComparableFloat(s), ComparableFloat(tree_t0.clone()));
            assert_eq!(oo, Equal);
        }
    } else {
        assert_panic!(x.tree_t0_prec_round_ref(prec, Exact));
    }

    // A `Float` that is not too large or too small gives the same result as the equal `Rational`.
    if x.is_normal() && exponent_in_gate(&x) {
        let (r, ro) = Float::tree_t0_rational_prec_round(Rational::exact_from(&x), prec, rm);
        assert_eq!(ComparableFloatRef(&r), ComparableFloatRef(&tree_t0));
        assert_eq!(ro, o);
    }
}

