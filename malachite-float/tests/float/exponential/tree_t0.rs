#[allow(clippy::needless_pass_by_value)]
fn tree_t0_rational_prec_round_properties_helper(x: Rational, prec: u64, rm: RoundingMode) {
    let (tree_t0, o) = Float::tree_t0_rational_prec_round(x.clone(), prec, rm);
    assert!(tree_t0.is_valid());
    assert_rounding_ordering_consistent(&tree_t0, rm, o);

    let (tree_t0_alt, o_alt) = Float::tree_t0_rational_prec_round_ref(&x, prec, rm);
    assert!(tree_t0_alt.is_valid());
    assert_eq!(
        ComparableFloatRef(&tree_t0_alt),
        ComparableFloatRef(&tree_t0)
    );
    assert_eq!(o_alt, o);

    // T(x) = -W(-x)
    let neg_x = -&x;
    let (w, wo) = Float::lambert_w0_rational_prec_round_ref(&neg_x, prec, -rm);
    // W_0 of a `Rational` zero is 0.0, and so is T_0 of one.
    let t = if x == 0u32 { w } else { -w };
    assert_eq!(ComparableFloatRef(&t), ComparableFloatRef(&tree_t0));
    assert_eq!(wo.reverse(), o);

    if rm != Exact && tree_t0.is_normal() && result_in_range(&tree_t0, o) {
        assert_lambert_w_correctly_rounded(
            true,
            &|f| f.partial_cmp(&neg_x).unwrap(),
            None,
            &float_to_big_exponent_float(&-&tree_t0),
            o.reverse(),
            prec,
            -rm,
        );
    }

    if tree_t0.is_normal() {
        assert_eq!(tree_t0.get_prec(), Some(prec));
    }
    if x <= 0u32 {
        assert_eq!(tree_t0.partial_cmp(&0u32), x.partial_cmp(&0u32));
    } else if tree_t0.is_normal() {
        assert!(tree_t0 >= 0u32);
        assert!(tree_t0 <= 1u32);
    }

    if o == Equal {
        for rm in exhaustive_rounding_modes() {
            let (s, oo) = Float::tree_t0_rational_prec_round_ref(&x, prec, rm);
            assert_eq!(ComparableFloat(s), ComparableFloat(tree_t0.clone()));
            assert_eq!(oo, Equal);
        }
    } else {
        assert_panic!(Float::tree_t0_rational_prec_round_ref(&x, prec, Exact));
    }
}

