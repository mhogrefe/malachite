        let x = parse_hex_string(s_hex);
        assert_eq!(x.to_string(), s);

        let (tree_t0, o) = x.clone().tree_t0_prec_round(prec, rm);
        assert!(tree_t0.is_valid());

        assert_eq!(tree_t0.to_string(), out);
        assert_eq!(to_hex_string(&tree_t0), out_hex);
        assert_eq!(o, o_out);

        let (tree_t0_alt, o_alt) = x.tree_t0_prec_round_ref(prec, rm);
