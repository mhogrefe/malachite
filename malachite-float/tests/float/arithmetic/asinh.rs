#[allow(clippy::type_repetition_in_bounds)]
fn primitive_float_asinh_properties_helper<T: PrimitiveFloat>()
where
    Float: From<T> + PartialOrd<T>,
    for<'a> T: ExactFrom<&'a Float> + RoundingFrom<&'a Float>,
{
    primitive_float_gen::<T>().test_properties(|x| {
        let c = primitive_float_asinh(x);
        // asinh is NaN exactly for NaN inputs, and otherwise has the sign of x and |asinh x| <=
        // |x|.
        assert_eq!(c.is_nan(), x.is_nan());
        if !x.is_nan() {
            assert_eq!(c.is_sign_positive(), x.is_sign_positive());
            assert!(c.abs() <= x.abs());
            // asinh is odd
            assert_eq!(NiceFloat(primitive_float_asinh(-x)), NiceFloat(-c));
        }
        if x.is_finite() {
            // the result is the correctly rounded inverse hyperbolic sine, as computed by MPFR at
            // the same precision; it never overflows.
            let rug_x = rug::Float::with_val(
                u32::exact_from(T::MANTISSA_WIDTH + 1),
                &rug::Float::exact_from(&Float::from(x)),
            );
            let rug_c = <Float as From<&rug::Float>>::from(&rug_x.asinh());
            let expected = T::exact_from(&rug_c);
            assert_eq!(NiceFloat(expected), NiceFloat(c));
        }
    });
}

