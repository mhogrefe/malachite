#[allow(clippy::needless_pass_by_value)]
fn csch_prec_round_properties_helper(x: Float, prec: u64, rm: RoundingMode) {
    let (c, o) = x.clone().csch_prec_round(prec, rm);
    assert!(c.is_valid());
    assert_rounding_ordering_consistent(&c, rm, o);

    let (c_alt, o_alt) = x.csch_prec_round_ref(prec, rm);
    assert!(c_alt.is_valid());
    assert_eq!(ComparableFloatRef(&c_alt), ComparableFloatRef(&c));
    assert_eq!(o_alt, o);

    let mut x_alt = x.clone();
    let o_alt = x_alt.csch_prec_round_assign(prec, rm);
    assert!(x_alt.is_valid());
    assert_eq!(ComparableFloatRef(&x_alt), ComparableFloatRef(&c));
    assert_eq!(o_alt, o);

    if let Ok(rug_rm) = rug_round_try_from_rounding_mode(rm) {
        let (rug_c, rug_o) = rug_csch_prec_round(&rug::Float::exact_from(&x), prec, rug_rm);
        assert_eq!(
            ComparableFloatRef(&Float::from(&rug_c)),
            ComparableFloatRef(&c)
        );
        assert_eq!(rug_o, o);
    }

    // csch is odd
    let (c_neg, o_neg) = (-&x).csch_prec_round(prec, -rm);
    assert_eq!(ComparableFloatRef(&c_neg), ComparableFloatRef(&-&c));
    assert_eq!(o_neg, o.reverse());

    // csch x has the sign of x
    if !x.is_nan() {
        assert_eq!(c.is_sign_positive(), x.is_sign_positive());
    }
    // |csch x| < |1/x| for finite nonzero x, so csch x is on the zero side of 1/x rounded the same
    // way
    if x.is_normal() {
        let r = x.reciprocal_prec_round_ref(prec, rm).0;
        if x > 0u32 {
            assert!(c <= r);
        } else {
            assert!(c >= r);
        }
    }
    if c.is_normal() {
        assert_eq!(c.get_prec(), Some(prec));
    }

    if o == Equal {
        // csch is exact only for x = ±0 (and NaN, and ±inf): the result is
        // rounding-mode-invariant
        for rm2 in exhaustive_rounding_modes() {
            let (c2, o2) = x.csch_prec_round_ref(prec, rm2);
            assert_eq!(ComparableFloat(c2), ComparableFloat(c.clone()));
            assert_eq!(o2, Equal);
        }
    } else {
        assert_panic!(x.csch_prec_round_ref(prec, Exact));
    }
}

