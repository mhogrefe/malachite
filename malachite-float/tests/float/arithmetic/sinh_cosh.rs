#[allow(clippy::needless_pass_by_value)]
fn sinh_cosh_prec_round_properties_helper(x: Float, prec: u64, rm: RoundingMode) {
    let (s, c, o_s, o_c) = x.clone().sinh_cosh_prec_round(prec, rm);
    assert!(s.is_valid());
    assert!(c.is_valid());
    assert_rounding_ordering_consistent(&s, rm, o_s);
    assert_rounding_ordering_consistent(&c, rm, o_c);

    let (s_alt, c_alt, o_s_alt, o_c_alt) = x.sinh_cosh_prec_round_ref(prec, rm);
    assert_eq!(ComparableFloatRef(&s_alt), ComparableFloatRef(&s));
    assert_eq!(ComparableFloatRef(&c_alt), ComparableFloatRef(&c));
    assert_eq!((o_s_alt, o_c_alt), (o_s, o_c));

    let mut s_alt = x.clone();
    let mut c_alt = Float::NAN;
    let o_alt = s_alt.sinh_cosh_prec_round_assign(&mut c_alt, prec, rm);
    assert_eq!(ComparableFloatRef(&s_alt), ComparableFloatRef(&s));
    assert_eq!(ComparableFloatRef(&c_alt), ComparableFloatRef(&c));
    assert_eq!(o_alt, (o_s, o_c));

    // the results are those of `sinh` and `cosh`
    let (s_alt, o_s_alt) = x.sinh_prec_round_ref(prec, rm);
    let (c_alt, o_c_alt) = x.cosh_prec_round_ref(prec, rm);
    assert_eq!(ComparableFloatRef(&s_alt), ComparableFloatRef(&s));
    assert_eq!(ComparableFloatRef(&c_alt), ComparableFloatRef(&c));
    assert_eq!((o_s_alt, o_c_alt), (o_s, o_c));

    rug_sinh_cosh_check(&x, prec, rm, &s, &c, o_s, o_c);

    if o_s == Equal && o_c == Equal {
        for rm2 in [Down, Up, Floor, Ceiling, Nearest, Exact] {
            let (s2, c2, o_s2, o_c2) = x.sinh_cosh_prec_round_ref(prec, rm2);
            assert_eq!(ComparableFloat(s2), ComparableFloat(s.clone()));
            assert_eq!(ComparableFloat(c2), ComparableFloat(c.clone()));
            assert_eq!((o_s2, o_c2), (Equal, Equal));
        }
    } else {
        assert_panic!(x.sinh_cosh_prec_round_ref(prec, Exact));
    }
}

