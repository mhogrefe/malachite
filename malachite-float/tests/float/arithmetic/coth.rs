#[allow(clippy::needless_pass_by_value)]
fn coth_prec_round_properties_helper(x: Float, prec: u64, rm: RoundingMode) {
    let (c, o) = x.clone().coth_prec_round(prec, rm);
    assert!(c.is_valid());
    assert_rounding_ordering_consistent(&c, rm, o);

    let (c_alt, o_alt) = x.coth_prec_round_ref(prec, rm);
    assert!(c_alt.is_valid());
    assert_eq!(ComparableFloatRef(&c_alt), ComparableFloatRef(&c));
    assert_eq!(o_alt, o);

    let mut x_alt = x.clone();
    let o_alt = x_alt.coth_prec_round_assign(prec, rm);
    assert!(x_alt.is_valid());
    assert_eq!(ComparableFloatRef(&x_alt), ComparableFloatRef(&c));
    assert_eq!(o_alt, o);

    if let Ok(rug_rm) = rug_round_try_from_rounding_mode(rm) {
        let (rug_c, rug_o) = rug_coth_prec_round(&rug::Float::exact_from(&x), prec, rug_rm);
        assert_eq!(
            ComparableFloatRef(&Float::from(&rug_c)),
            ComparableFloatRef(&c)
        );
        assert_eq!(rug_o, o);
    }

    // coth is odd
    let (c_neg, o_neg) = (-&x).coth_prec_round(prec, -rm);
    assert_eq!(ComparableFloatRef(&c_neg), ComparableFloatRef(&-&c));
    assert_eq!(o_neg, o.reverse());

    // coth x has the sign of x
    if !x.is_nan() {
        assert_eq!(c.is_sign_positive(), x.is_sign_positive());
    }
    // |coth x| > |1/x| for finite nonzero x, so coth x is on the far side of 1/x rounded the same
    // way, and |coth x| > 1
    if x.is_normal() {
        let r = x.reciprocal_prec_round_ref(prec, rm).0;
        if x > 0u32 {
            assert!(c >= r);
            assert!(c >= 1u32);
        } else {
            assert!(c <= r);
            assert!(c <= -1i32);
        }
    }
    if c.is_normal() {
        assert_eq!(c.get_prec(), Some(prec));
    }

    if o == Equal {
        // coth is exact only for x = ±0 and ±inf (and NaN): the result is rounding-mode-invariant
        for rm2 in exhaustive_rounding_modes() {
            let (c2, o2) = x.coth_prec_round_ref(prec, rm2);
            assert_eq!(ComparableFloat(c2), ComparableFloat(c.clone()));
            assert_eq!(o2, Equal);
        }
    } else {
        assert_panic!(x.coth_prec_round_ref(prec, Exact));
    }
}

