#[allow(clippy::type_repetition_in_bounds)]
fn primitive_float_coth_rational_properties_helper<T: PrimitiveFloat>()
where
    Float: From<T> + PartialOrd<T>,
    Rational: ExactFrom<T>,
    for<'a> T: ExactFrom<&'a Float> + RoundingFrom<&'a Float>,
{
    rational_gen().test_properties(|x| {
        let c = primitive_float_coth_rational::<T>(&x);
        // the hyperbolic cotangent of a rational is never NaN
        assert!(!c.is_nan());
        if x != 0u32 {
            // coth x has the sign of x, and coth is odd
            assert_eq!(c.is_sign_positive(), x > 0u32);
            assert!(c >= T::ONE || c <= T::NEGATIVE_ONE);
            assert_eq!(
                NiceFloat(primitive_float_coth_rational::<T>(&-&x)),
                NiceFloat(-c)
            );
        }
        // the result is the correctly rounded hyperbolic cotangent, as computed by MPFR with bits
        // to spare, so that a subnormal result is rounded once by the conversion rather than twice.
        // For a tiny x, coth x = 1/x + x/3 + ... lies within about x^2 (relatively) of 1/x, which
        // may be exactly halfway between two `T`s, so the spare bits must also resolve that gap.
        let spare = if x == 0u32 {
            64
        } else {
            64 + (x.floor_log_base_2_abs().unsigned_abs() << 1)
        };
        let rug_c = rug_coth_rational_prec(&x, T::MANTISSA_WIDTH + spare).0;
        let rug_c: T = T::rounding_from(&<Float as From<&rug::Float>>::from(&rug_c), Nearest).0;
        assert_eq!(NiceFloat(rug_c), NiceFloat(c));
    });

    primitive_float_gen::<T>().test_properties(|x| {
        // The hyperbolic cotangent of a finite nonzero primitive float, taken through the
        // `Rational` path, matches the direct primitive-float hyperbolic cotangent. (Zero is
        // excluded, since a `Rational` has no negative zero.)
        if x.is_finite() && x != T::ZERO {
            assert_eq!(
                NiceFloat(primitive_float_coth_rational::<T>(&Rational::exact_from(x))),
                NiceFloat(primitive_float_coth(x))
            );
        }
    });
}

