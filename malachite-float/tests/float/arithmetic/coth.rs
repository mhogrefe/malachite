#[allow(clippy::type_repetition_in_bounds)]
fn primitive_float_coth_properties_helper<T: PrimitiveFloat>()
where
    Float: From<T> + PartialOrd<T>,
    for<'a> T: ExactFrom<&'a Float> + RoundingFrom<&'a Float>,
{
    primitive_float_gen::<T>().test_properties(|x| {
        let c = primitive_float_coth(x);
        // coth is NaN exactly for NaN inputs, and otherwise has the sign of its input and magnitude
        // at least 1
        assert_eq!(c.is_nan(), x.is_nan());
        if !x.is_nan() {
            assert_eq!(c.is_sign_positive(), x.is_sign_positive());
            assert!(c >= T::ONE || c <= T::NEGATIVE_ONE);
            // coth is odd
            assert_eq!(NiceFloat(primitive_float_coth(-x)), NiceFloat(-c));
        }
        if x.is_finite() {
            // the result is the correctly rounded hyperbolic cotangent, as computed by MPFR with 64
            // bits to spare, so that a subnormal result is rounded once by the conversion rather
            // than twice
            let rug_c = rug_coth_prec(
                &rug::Float::exact_from(&Float::from(x)),
                T::MANTISSA_WIDTH + 64,
            )
            .0;
            let rug_c: T = T::rounding_from(&<Float as From<&rug::Float>>::from(&rug_c), Nearest).0;
            assert_eq!(NiceFloat(rug_c), NiceFloat(c));
        }
    });
}

