#[test]
fn test_coth_rational_extreme() {
    // |x| = 2^(-2^30 - 10) is too small to be a `Float`; coth(x) is just above 2^(2^30 + 10),
    // beyond the largest finite `Float`, so it overflows
    let x = Rational::power_of_2(-(1i64 << 30) - 10);
    let max = Float::max_finite_value_with_prec(10);
    for (rm, out, o_out) in [
        (Floor, max.clone(), Less),
        (Down, max.clone(), Less),
        (Nearest, Float::INFINITY, Greater),
        (Ceiling, Float::INFINITY, Greater),
        (Up, Float::INFINITY, Greater),
    ] {
        let (c, o) = Float::coth_rational_prec_round_ref(&x, 10, rm);
        assert_eq!(ComparableFloatRef(&c), ComparableFloatRef(&out));
        assert_eq!(o, o_out);
        let (c_neg, o_neg) = Float::coth_rational_prec_round(-&x, 10, -rm);
        assert_eq!(ComparableFloat(c_neg), ComparableFloat(-c));
        assert_eq!(o_neg, o.reverse());
    }

    // |x| = 2^(2^30) is too large to be a `Float`, and coth(x) is within 2^(-2^31) of 1, above it
    let x = Rational::power_of_2(1i64 << 30);
    let (c, o) = Float::coth_rational_prec_round_ref(&x, 10, Nearest);
    assert_eq!(ComparableFloat(c), ComparableFloat(Float::one_prec(10)));
    assert_eq!(o, Less);
    let (c, o) = Float::coth_rational_prec_round(-x, 10, Up);
    assert_eq!(c.to_string(), "-1.0020");
    assert_eq!(c.get_prec(), Some(10));
    assert_eq!(o, Less);
}

