fn log_base_big_exponent_float_base_prec_round_properties_helper(
    x: &BigExponentFloat,
    b: &BigExponentFloat,
    prec: u64,
    rm: RoundingMode,
) {
    let r = log_base_big_exponent_float_base_prec_round_all(x, b, prec, rm);
    if !r.0.is_finite() || r.0.is_zero() {
        assert_eq!(r.1, Equal);
    } else {
        assert!(r.0.get_prec().unwrap() <= prec);
    }
    if rm == Exact {
        assert_eq!(r.1, Equal);
    } else if !r.0.is_nan() {
        // The result lies between the results rounded down and up.
        let floor = log_base_big_exponent_float_base_prec_round_all(x, b, prec, Floor);
        let ceiling = log_base_big_exponent_float_base_prec_round_all(x, b, prec, Ceiling);
        assert!(floor.0 <= r.0 && r.0 <= ceiling.0);
        assert_ne!(floor.1, Greater);
        assert_ne!(ceiling.1, Less);
        if r.1 == Equal {
            assert!(same_pair(
                &log_base_big_exponent_float_base_prec_round_all(x, b, prec, Exact),
                &r
            ));
        }
        // Rounding in one direction twice is rounding once.
        if rm != Nearest {
            let (y, o) = log_base_big_exponent_float_base_prec_round_all(x, b, prec + 16, rm);
            let (z, oz) = y.round_to_prec_round(prec, rm);
            assert!(same(&z, &r.0));
            assert_eq!(if o == Equal { oz } else { o }, r.1);
        }
    }
    // An integer base gives the same result as the `u64` base.
    if let Ok(k) = u64::try_from(b)
        && k > 1
    {
        assert!(same_pair(&r, &x.log_base_prec_round_ref(k, prec, rm)));
    }
    // A base of 1 gives NaN, as in `arf_div`, since ln(1) = 0 and there is no signed zero.
    if *b == 1u32 {
        assert!(r.0.is_nan());
    }
}

