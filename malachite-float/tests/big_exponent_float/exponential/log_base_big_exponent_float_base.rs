#[test]
fn log_base_big_exponent_float_base_prec_round_float_agreement_properties() {
    float_float_unsigned_rounding_mode_quadruple_gen_var_11().test_properties(
        |(x, b, prec, rm)| {
            if rm == Exact {
                return;
            }
            let (f, fo) = x.log_base_float_base_prec_round_ref(&b, prec, rm);
            if float_result_comparable(&f, fo) && b != 1u32 {
                let r = log_base_big_exponent_float_base_prec_round_all(
                    &float_to_big_exponent_float(&x),
                    &float_to_big_exponent_float(&b),
                    prec,
                    rm,
                );
                assert!(same(&r.0, &float_to_big_exponent_float(&f)));
                assert_eq!(r.1, fo);
            }
        },
    );
}
