use itertools::Itertools;
use malachite_base::random::EXAMPLE_SEED;
use malachite_base::u64_polynomial::random::*;

fn striped_random_u64_polynomials_degree_range_helper(
    a: u64,
    b: u64,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
    expected_values: &[&str],
) {
    assert_eq!(
        striped_random_u64_polynomials_degree_range(
            EXAMPLE_SEED,
            a,
            b,
            mean_stripe_numerator,
            mean_stripe_denominator
        )
        .take(20)
        .map(|p| p.to_string())
        .collect_vec(),
        expected_values
    );
}

