use itertools::Itertools;
use malachite_base::random::EXAMPLE_SEED;
use malachite_base::u64_polynomial::random::*;

fn random_u64_polynomials_with_degree_helper(degree: u64, expected_values: &[&str]) {
    assert_eq!(
        random_u64_polynomials_with_degree(EXAMPLE_SEED, degree)
            .take(20)
            .map(|p| p.to_string())
            .collect_vec(),
        expected_values
    );
}

