// `a` with its first two rows swapped.
fn swap_first_rows(a: &UnsignedMatrix<u64>) -> UnsignedMatrix<u64> {
    let n = a.height();
    let mut rows: Vec<Vec<u64>> = (0..n).map(|i| a.row_iter(i).copied().collect()).collect();
    rows.swap(0, 1);
    UnsignedMatrix::from_owned_elements(n, n, rows.concat())
}

#[test]
fn mod_determinant_properties() {
    unsigned_matrix_unsigned_pair_gen_var_11().test_properties(|(a, m)| {
        let d = (&a).mod_determinant(m);
        assert_eq!(a.clone().mod_determinant(m), d);
        assert!(d < m);
        assert_eq!(unsigned_matrix_mod_determinant_berkowitz(&a, m), d);
        assert_eq!(unsigned_matrix_mod_determinant_howell::<u64, i64>(&a, m), d);
        if a.height() <= 6 {
            assert_eq!(unsigned_matrix_mod_determinant_naive(&a, m), d);
        }
        assert_eq!(a.transpose().mod_determinant(m), d);
        let at = a.transpose();
        assert_eq!((&a).mod_mul(&at, m).mod_determinant(m), d.mod_mul(d, m));
        if a.height() >= 2 {
            assert_eq!(swap_first_rows(&a).mod_determinant(m), d.mod_neg(m));
        }
    });

    unsigned_matrix_unsigned_pair_gen_var_12().test_properties(|(a, m)| {
        let d = (&a).mod_determinant(m);
        assert_eq!(unsigned_matrix_mod_determinant_lu(&a, m), d);
        assert_eq!(unsigned_matrix_mod_determinant_howell::<u64, i64>(&a, m), d);
    });
}
