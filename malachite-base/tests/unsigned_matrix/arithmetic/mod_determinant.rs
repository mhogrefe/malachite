fn test<T: PrimitiveUnsigned>(a: &str, m: T, out: T)
where
    <UnsignedMatrix<T> as FromStr>::Err: Debug,
    UnsignedMatrix<T>: ModDeterminant<T, Output = T>,
    for<'a> &'a UnsignedMatrix<T>: ModDeterminant<T, Output = T>,
{
    let a = UnsignedMatrix::<T>::from_str(a).unwrap();
    let d = (&a).mod_determinant(m);
    assert_eq!(d, out);
    assert_eq!(a.clone().mod_determinant(m), d);
    assert_eq!(unsigned_matrix_mod_determinant_berkowitz(&a, m), d);
}

