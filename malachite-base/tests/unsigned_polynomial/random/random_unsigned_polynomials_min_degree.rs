use itertools::Itertools;
use malachite_base::random::EXAMPLE_SEED;
use malachite_base::unsigned_polynomial::random::*;

fn random_unsigned_polynomials_min_degree_helper(
    min_degree: u64,
    mean_length_numerator: u64,
    mean_length_denominator: u64,
    expected_values: &[&str],
) {
    assert_eq!(
        random_unsigned_polynomials_min_degree::<u64>(
            EXAMPLE_SEED,
            min_degree,
            mean_length_numerator,
            mean_length_denominator
        )
        .take(20)
        .map(|p| p.to_string())
        .collect_vec(),
        expected_values
    );
}

