use itertools::Itertools;
use malachite_base::random::EXAMPLE_SEED;
use malachite_base::unsigned_polynomial::random::*;

fn striped_random_unsigned_polynomials_with_degree_helper(
    degree: u64,
    mean_stripe_numerator: u64,
    mean_stripe_denominator: u64,
    expected_values: &[&str],
) {
    assert_eq!(
        striped_random_unsigned_polynomials_with_degree::<u64>(
            EXAMPLE_SEED,
            degree,
            mean_stripe_numerator,
            mean_stripe_denominator
        )
        .take(20)
        .map(|p| p.to_string())
        .collect_vec(),
        expected_values
    );
}

